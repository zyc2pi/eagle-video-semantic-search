const assert = require('assert');
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const context = {};
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../js/manualAdd.js'), 'utf8') + '\nthis.scores = SceneScores;', context);
const { valid, adjust, references, nextUnscored } = context.scores;
assert(valid(0)); assert(valid(101)); assert(!valid(null)); assert(!valid(-1)); assert(!valid(NaN)); assert(!valid(Infinity));
assert.strictEqual(adjust(12.3, 1), 12.4);
assert.strictEqual(adjust(12.3, -1), 12.2);
assert.strictEqual(adjust(12.3, 1, true), 13.3);
assert.strictEqual(adjust(12.3, -1, true), 11.3);
assert.strictEqual(adjust(0, -1), 0);
assert.strictEqual(adjust(null, 1), 0.1);
let score = 10;
for (let i = 0; i < 100; i += 1) score = adjust(score, 1);
assert.strictEqual(score, 20, '反复按键不积累浮点误差');
assert.strictEqual(adjust(Number.MAX_VALUE, 1, true), Number.MAX_VALUE);
const matches = [30.25, 14, 20, 2, 100, NaN].map((similarity) => ({ similarity }));
const refs = references(matches);
assert.deepStrictEqual(Array.from(refs, ({ match }) => match.similarity), [100, 20, 2]);
assert.strictEqual(matches[0].similarity, 30.25, '取参考不改变主题的原排序');
assert.strictEqual(references([]).length, 0);
assert.strictEqual(references([{ similarity: 0 }]).length, 1);
assert.strictEqual(references([{ similarity: 20 }, { similarity: 10 }]).length, 2);
assert.strictEqual(references([{ similarity: -1 }, {}]).length, 0);
assert.strictEqual(nextUnscored([{ value: 0 }, { value: null }, { value: 12 }], 2), 1, '未评分跳转循环回到前面');
assert.strictEqual(nextUnscored([{ value: null }, { value: 12 }], 0), 0, '只剩当前空白时定位自身');
assert.strictEqual(nextUnscored([{ value: 0 }, { value: 12 }], 0), -1, '零分属于已填写分数');
assert.strictEqual(nextUnscored([], 0), -1);
console.log('manual score reference sampling and precise keyboard increments passed');
